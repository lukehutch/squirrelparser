// _rprofile.dart -- where does m121's time actually go, round by round?
//
// WHY THIS EXISTS. The latency plan (a cost-stratified semi-naive deductive
// chart) rests on ONE claim: the repair memo is cleared at the top of every
// deepening round (`m121.dart:570-571`), so round b re-derives everything round
// b-1 already derived, and eliminating that redundancy is the win.
//
// That is an assumption and it has a cheap falsifier. If the round that
// SUCCEEDS dominates the clock, then all earlier rounds together are a small
// share, the redundancy is small, and the rewrite's ceiling is small -- the plan
// would be wrong before a line of it is written. Measure before building.
//
// `_m124r.dart` is m121 with a per-round stopwatch and nothing else changed;
// it is generated by `mkrounds.py` so it cannot drift from the engine by hand.
//
// Usage: dart run _rprofile.dart
import 'package:squirrel_parser/squirrel_parser.dart';

import 'astdiff.dart';
import '_m124r.dart' as g;

void main() {
  final cases = weighted(buildBattery());
  final rulesOf = <String, Map<String, Clause>>{
    for (final c in corpora) c.name: MetaGrammar.parseGrammar(c.grammar)
  };
  final made = <String, MatchResult? Function(String)>{
    for (final c in corpora)
      c.name: g.SuperDot3(rules: rulesOf[c.name]!, topRuleName: c.top).recover
  };

  for (final k in cases) {
    try {
      made[k.grammar]!(k.mutant);
    } catch (_) {}
  }

  final us = g.kRoundUs, hits = g.kRoundHits, wins = g.kWinRound;
  final total = us.fold<int>(0, (a, b) => a + b);
  final totalWins = wins.fold<int>(0, (a, b) => a + b);
  print('m121 over ${cases.length} weighted cases: '
      '${(total / 1000).round()} ms in the deepening loop\n');
  print('ord   budget      ms     % of total   entered   won here');
  print('---   ------   -----   ------------   -------   --------');
  for (var i = 0; i < us.length; i++) {
    if (hits[i] == 0) continue;
    final budget = i == 0 ? 0 : 1 << (i - 1);
    print('${i.toString().padLeft(3)}   '
        '${budget.toString().padLeft(6)}   '
        '${(us[i] / 1000).round().toString().padLeft(5)}   '
        '${(100 * us[i] / total).toStringAsFixed(1).padLeft(7)}%     '
        '${hits[i].toString().padLeft(7)}   '
        '${wins[i].toString().padLeft(8)}');
  }
  print('\n$totalWins of ${cases.length} cases produced a tree');

  // THE DECISIVE NUMBER. A round that does NOT win its case derived facts that
  // the next round throws away and derives again. That time is the ceiling on
  // what the semi-naive rewrite could save -- it cannot save any part of the
  // round that actually produced the answer.
  //
  // Attribute per round ordinal: of the calls that ENTERED round i, the ones
  // that went on to a deeper round did so having wasted round i entirely.
  // Measured EXACTLY, per call, not apportioned. An earlier version split each
  // round's clock in proportion to how many of its entrants went deeper, which
  // silently assumes every case costs the same within a round -- and the cases
  // that go deeper are the harder ones, so that assumption is not neutral.
  final wasted = g.kWastedUs, productive = g.kProdUs;
  print('\nRe-derived (rounds whose result was discarded): '
      '${(wasted / 1000).round()} ms, '
      '${(100 * wasted / total).toStringAsFixed(1)}% of the loop.');
  print('Productive (the round that answered):            '
      '${(productive / 1000).round()} ms, '
      '${(100 * productive / total).toStringAsFixed(1)}%.');
  print('\nCEILING: a rewrite that never re-derives can remove at most the '
      'first figure. Anything beyond that must come from making the '
      'productive round itself cheaper.');
}
