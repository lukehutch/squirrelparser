#!/usr/bin/env python3
"""m126 = m125 + I75: round the residual UP to the deepening ladder, so the
number of live memo families is logarithmic and the tables stay shared.

I74 gave every budget its own memo family so a fold could search at the residual.
Measured round by round against m124 (`_rprofile125.dart`), it is two results,
not one:

    ord budget   m124 ms   m125 ms
      1      1       224       252
      2      2       966       234     4.1x FASTER
      3      4       774       361     2.1x faster
      4      8       464       377
      5     16       560      1459     2.6x SLOWER  <-- 53% of the clock, 7 cases

The regression is structural and it is the exact price of the win. At budget 2
the residuals are {0,1,2}: three families, all cheap. At budget 16 they are
{0..16}: seventeen families, several of them expensive, where m121 had ONE table
that every caller shared no matter what the residual was. I74 buys a cheaper
search per call by giving up the sharing BETWEEN calls at different residuals.

I75. Both halves are wanted, and the ladder the deepening loop already walks
supplies them. Round the residual UP to the next rung -- 0,1,2,4,8,16,... -- so
the families are O(log budget) instead of O(budget), and every rung is shared by
the whole range of residuals that reach it. Searching at a budget ABOVE the
residual is what the engine did all along, so this is sound for the reason I74
was: the fold's `cost > _budget` filter still discards anything the residual
cannot afford, and it is tested against the FULL budget, which is what the way
must actually fit inside.

No new constant. The rungs are the schedule already in `recover`, so this adds a
rule, not a tuning parameter.
"""

D = '/home/luke/Work/squirrelparser/dart/experiments/recovery/'
src = open(D + 'm125.dart', encoding='utf-8').read()

head = '''// m126.dart -- I75: the residual is rounded up to the deepening ladder, so the
// memo families are logarithmic in the budget and stay shared across residuals.
// Generated by mk126.py from m125.dart.
'''
assert src.startswith('// m125.dart --')
src = head + src[src.index('\n') + 1:]

# ------------------------------------------------------------------ the rung
anchor = '''  /// Make the families reach [b].'''
assert src.count(anchor) == 1
src = src.replace(anchor, '''  /// I75: THE LADDER IS ALREADY THERE, SO USE IT FOR THE RESIDUALS TOO.
  ///
  /// The smallest rung of the deepening schedule that is at least [r]. Searching
  /// above the residual is sound -- it is what the engine did before I74 -- and
  /// rounding to the rungs keeps the number of live families logarithmic in the
  /// budget instead of linear, so a residual-13 call and a residual-16 call
  /// share one table rather than building two.
  int _rung(int r) {
    if (r <= 2) return r;
    var b = 4;
    while (b < r) {
      b *= 2;
    }
    return b;
  }

''' + anchor)

# ------------------------------------------------------------- the two folds
old_seq = '''        final full = _budget;
        _budget = full - w.cost;
        final from = _element(sub, w.end);'''
assert src.count(old_seq) == 1
src = src.replace(old_seq, '''        final full = _budget;
        _budget = _rung(full - w.cost);
        final from = _element(sub, w.end);''')

old_rep = '''      final full = _budget;
      _budget = full - w.cost;
      final from = _element(r.subClause, at);'''
assert src.count(old_rep) == 1
src = src.replace(old_rep, '''      final full = _budget;
      _budget = _rung(full - w.cost);
      final from = _element(r.subClause, at);''')

out = D + 'm126.dart'
open(out, 'w', encoding='utf-8').write(src)
print('wrote', out)
