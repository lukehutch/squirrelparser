#!/usr/bin/env python3
"""m125 = m121 + I74: the memo belongs to the BUDGET, not to the round -- so the
fold can ask for what the prefix can still afford.

I73 (m124) was the residual-0 case of this: a prefix that has spent the whole
budget can only be continued for free, so it asks the pure table. Measured, that
collapsed round 1 from 1,716 ms to 224 (7.7x) and left every later round
untouched -- exactly as it must, because at budget 1 EVERY cost-1 prefix has
residual 0, while at budget 2 a cost-1 prefix has residual 1 and I73 never fires.

I74 is the general rule. The ways at (clause, position) are a function of the
BUDGET alone -- every budget-sensitive test in the engine reads `_budget` and
nothing else -- so a table built at budget b is correct at budget b forever.
Give each budget its own table and the fold can search at the residual instead
of the round's whole budget. Every way that costs more than the residual was
being discarded unread anyway, so nothing is lost.

Two consequences, and the second was not the goal:

 1. WITHIN the round, a residual-r element runs an r-budget search rather than a
    b-budget one. Round 1 costs 224 ms where round 2 costs 966, so the smaller
    search is worth a great deal.
 2. ACROSS rounds, round 2's residual-1 lookups land in the table round 1 already
    filled. That is the cross-round redundancy the semi-naive plan was going to
    be rewritten to eliminate -- 28.4% of the loop -- arriving as a side effect
    of a change made for a different reason. Only partly: round 4 needs tables 3
    and 4, which no round built.

I73's explicit `_pure` special case DISAPPEARS -- residual 0 sets `_budget` to 0,
and `_element` at budget 0 is already `_clause` on `_pc`, which is `_pure`. So
this is generated from m121, not from m124: the general rule is also the smaller
one.
"""

D = '/home/luke/Work/squirrelparser/dart/experiments/recovery/'
src = open(D + 'm121.dart', encoding='utf-8').read()

head = '''// m125.dart -- I74: the memo belongs to the budget, not to the round, so a fold
// can search at what the prefix can still afford. Subsumes m124's I73.
// Generated by mk125.py from m121.dart.
'''
assert src.startswith('// m121.dart --')
src = head + src[src.index('\n') + 1:]

# ------------------------------------------------------- 1. the memo families
old_fields = '''  /// Left-recursion generation stamps, one array per memo family, because the
  /// pure tables outlive the round tables and must not be invalidated by them.
  List<int> _pg = const [], _rg = const [];'''
assert src.count(old_fields) == 1
new_fields = '''  /// Left-recursion generation stamps, one array per memo family, because the
  /// pure tables outlive the round tables and must not be invalidated by them.
  List<int> _pg = const [];
  final List<List<int>> _rg = [];'''
src = src.replace(old_fields, new_fields)

old_tables = '''  /// `_pc` holds the BUDGET-0 answer -- the frozen parser's -- which cannot
  /// depend on the budget, so it is solved once per input and shared by every
  /// round. `_mc`/`_me` hold the answer under this round's budget and are
  /// cleared when it changes. There is no budget-0 element table: with no
  /// repair allowed, an element IS its clause, so it would duplicate `_pc`.
  final Map<Clause, List<_Cell?>> _pc = HashMap.identity(),
      _mc = HashMap.identity(),
      _me = HashMap.identity();'''
assert src.count(old_tables) == 1
new_tables = '''  /// `_pc` holds the BUDGET-0 answer -- the frozen parser's -- which cannot
  /// depend on the budget, so it is solved once per input and shared by every
  /// round. There is no budget-0 element table: with no repair allowed, an
  /// element IS its clause, so it would duplicate `_pc`.
  final Map<Clause, List<_Cell?>> _pc = HashMap.identity();

  /// I74: ONE FAMILY PER BUDGET, NOT ONE PER ROUND. What a clause can do at a
  /// position is a function of the budget alone -- every budget-sensitive test
  /// in this engine reads `_budget` and nothing else -- so a table built at
  /// budget b is still correct at budget b in every later round. Indexing by
  /// budget is what lets [_seq] and [_rep] ask for the residual, and it also
  /// means round 2's residual-1 lookups land in the table round 1 filled.
  final List<Map<Clause, List<_Cell?>>> _mc = [], _me = [];

  /// Make the families reach [b]. Only the deepening loop needs to call this: a
  /// residual is never larger than the budget it is subtracted from, so every
  /// budget the folds ask for has already been made.
  void _room(int b) {
    while (_mc.length <= b) {
      _mc.add(HashMap.identity());
      _me.add(HashMap.identity());
      _rg.add(List.filled(_in.length + 1, 0));
    }
  }'''
src = src.replace(old_tables, new_tables)

# ------------------------------------------------------------ 2. the lookups
old_clause = '      : _fix(_budget == 0 ? _pc : _mc, c, pos, _expand);'
assert src.count(old_clause) == 1
src = src.replace(old_clause,
                  '      : _fix(_budget == 0 ? _pc : _mc[_budget], c, pos, _expand);')

old_elem = '      _budget == 0 ? _clause(c, pos) : _fix(_me, c, pos, _repair);'
assert src.count(old_elem) == 1
src = src.replace(old_elem,
                  '      _budget == 0 ? _clause(c, pos) : _fix(_me[_budget], c, pos, _repair);')

old_gen = '    final gen = _budget == 0 ? _pg : _rg;'
assert src.count(old_gen) == 1
src = src.replace(old_gen, '    final gen = _budget == 0 ? _pg : _rg[_budget];')

# --------------------------------------------------------- 3. the round setup
old_loop = '''      _mc.clear();
      _me.clear();
      _rg = List.filled(s.length + 1, 0);
'''
assert src.count(old_loop) == 1
src = src.replace(old_loop, '''      _room(_budget);
''')

old_reset = '''    _pc.clear();
    _pg = List.filled(s.length + 1, 0);'''
assert src.count(old_reset) == 1
src = src.replace(old_reset, '''    _pc.clear();
    _mc.clear();
    _me.clear();
    _rg.clear();
    _pg = List.filled(s.length + 1, 0);''')

# ------------------------------------------------------------- 4. the folds
note = '''        // I74: ASK FOR WHAT THE PREFIX CAN STILL AFFORD. `w` has spent
        // `w.cost` of the round's budget, so every way costing more than the
        // rest is discarded two lines below, unread -- and a search at the
        // residual cannot produce one. At residual 0 this is `_pure`: with
        // nothing left to spend, `_element` is `_clause` on the pure table.
'''
old_seq = '''      for (var w = ways; w != null; w = w.next) {
        for (var x = _element(sub, w.end); x != null; x = x.next) {'''
assert src.count(old_seq) == 1
new_seq = '''      for (var w = ways; w != null; w = w.next) {
''' + note + '''        final full = _budget;
        _budget = full - w.cost;
        final from = _element(sub, w.end);
        _budget = full;
        for (var x = from; x != null; x = x.next) {'''
src = src.replace(old_seq, new_seq)

old_rep = '''      final w = _at(reach, at)!;
      for (var x = _element(r.subClause, at); x != null; x = x.next) {'''
assert src.count(old_rep) == 1
new_rep = '''      final w = _at(reach, at)!;
      final full = _budget;
      _budget = full - w.cost;
      final from = _element(r.subClause, at);
      _budget = full;
      for (var x = from; x != null; x = x.next) {'''
src = src.replace(old_rep, new_rep)

out = D + 'm125.dart'
open(out, 'w', encoding='utf-8').write(src)
print('wrote', out)
