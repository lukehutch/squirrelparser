#!/usr/bin/env python3
r"""m132/m133/m134 = I78: invention may COMPLETE a shape the input witnesses; it
may not CONJURE one the input does not witness at all.

WHERE THIS COMES FROM. I76 (m127) let a repair-opened alternative compete at an
ending the evidence reaches only by repairing, which turned the deleted-`{`
document from a cost-11 String swallow into `FILL@0 "{"`, cost 1. It also lost
`truncate`, and the worst case shows the same swallow entering from the other
side -- on `[1,[2,[3,[4`:

    m126  cost=4  FILL@11 "]" x4            <- right
    m127  cost=2  FILL@0 "\"" FILL@11 "\""  <- reads it as the String "[1,[2,[3,[4"

I77 cannot settle this and measurement confirmed it did not: the deepening ladder
returns at the FIRST budget that succeeds, so a cost-2 reading is accepted before
a cost-4 one is ever built. A comparison key only breaks ties WITHIN a round.

THE DISCRIMINATOR. Look at what the two repair-opened ways actually contain.

    deleted `{`   Object <- '{' Members '}'   the `{` is filled, the `}` is REAL,
                  and every key, colon and value inside is real
    truncation    String <- '"' Char* '"'     BOTH quotes are filled, and the
                  eleven characters between them go through `[^"\\]`

The first completes a shape the input plainly witnesses. The second conjures a
shape nothing in the input witnesses: strip the two invented quotes and there is
no evidence a String was ever there. That is what I43 was trying to say with "a
repair may not make the choice" -- but it tested where a way OPENS, a
one-character proxy that is wrong in both directions: it refused the brace (whose
partner is real) and admitted the swallow (whose delimiters are both invented).

I78. The engine already carries the right measure and does not need a new one.
[_Way.net] (I44) counts characters matched by a terminal THAT CONSTRAINS WHAT IT
ACCEPTS, and a fill contributes `got: 0, net: 0` (m127.dart:845), so `net` is
exactly "real input characters this way explained". Therefore:

    swallow      two filled quotes + 11 chars through an inverted set  ->  net == 0
    brace reading  real keys, colons, numbers, the real `}`            ->  net >> 0

So a repair-opened alternative is admitted only where `net > 0` -- only where the
input witnesses the shape the repair is completing. One condition, no new
counter, no new constant, and it states I43's own intent sharply enough that the
proxy can go.

VARIANTS (I77 is orthogonal, so measure I78 against each key):

  m132  m127 + I78                    (I76 + I78, cost as the first key)
  m133  m129 + I78                    (+ I77 as cost + got - net)
  m134  m130 + I78                    (+ I77 as cost - net)
"""
import sys

D = '/home/luke/Work/squirrelparser/dart/experiments/recovery/'

def _body(src):
    """Index just past the whole leading `//` header block, so a regenerated
    engine does not inherit the headers of every engine it was derived from."""
    i = 0
    for line in src.split('\n'):
        if not line.startswith('//'):
            break
        i += len(line) + 1
    return i



OLD = '''  for (_Way? e = opened; e != null; e = e.next) {
    final rival = _at(out, e.end);
    if (rival == null || rival.cost > 0) out = _put(out, _cons(e, null));
  }'''

NEW = r'''  for (_Way? e = opened; e != null; e = e.next) {
    // I78: THE INPUT MUST WITNESS THE SHAPE THE REPAIR IS COMPLETING.
    //
    // `net` counts real input characters matched by a terminal that constrains
    // what it accepts, and a fill contributes none, so `net == 0` says this way
    // rests on invention alone. Filling a `{` whose `}` is real, in front of
    // real keys and values, is completing a shape the input witnesses. Filling
    // BOTH quotes of a String and reading eleven structured characters through
    // `[^"\\]` conjures a shape nothing witnesses -- strip the invented quotes
    // and no evidence of a String remains. That is what I43 meant by "a repair
    // may not make the choice"; testing where a way OPENS was a proxy that got
    // it wrong in both directions.
    if (e.net == 0) continue;
    final rival = _at(out, e.end);
    if (rival == null || rival.cost > 0) out = _put(out, _cons(e, null));
  }'''

BASE = {'m132': 'm127', 'm133': 'm129', 'm134': 'm130'}
HEAD = {
    'm132': '// m132.dart -- I78: a repair-opened alternative is admitted only where the input\n'
            '// witnesses it (net > 0). Generated by mk132.py from m127.dart.\n',
    'm133': '// m133.dart -- I76 + I77 (cost + got - net) + I78.\n'
            '// Generated by mk132.py from m129.dart.\n',
    'm134': '// m134.dart -- I76 + I77 (cost - net) + I78.\n'
            '// Generated by mk132.py from m130.dart.\n',
}

for name in (sys.argv[1:] or ['m132', 'm133', 'm134']):
    base = BASE[name]
    src = open(D + base + '.dart', encoding='utf-8').read()
    assert src.startswith('// ' + base + '.dart --')
    src = HEAD[name] + src[_body(src):]
    assert src.count(OLD) == 1, name
    src = src.replace(OLD, NEW)
    open(D + name + '.dart', 'w', encoding='utf-8').write(src)
    print('wrote', D + name + '.dart')
