#!/usr/bin/env python3
"""m124 = m121 + I73: a prefix that has spent the budget can only be continued
by a reading that costs nothing, so ask the pure table, not the repair search.

WHY. `_seq` and `_rep` both fold left over the ways, and both ask the next
element for a search at the FULL budget before discarding whatever does not fit
in what the prefix left (`if (cost > _budget) continue`). When the prefix has
already spent the budget the residual is 0, so the ONLY ways that can survive
are the cost-0 ones -- and the cost-0 ways are exactly what `_pure` returns,
from a table (`_pc`) that is already built, already complete and already shared.
The whole repair search under such a call is answered and thrown away.

MEASURED FIRST (`_resid.dart` on `_r121b.dart`, generated by `mkresid.py`):
37.4% of the 15.0M fold calls have residual 0 while the budget is positive; they
return 9.81M ways of which 5.75M -- 58.6% -- are discarded unread; and the
non-overlapping wall time of the subtrees beneath them is 2,776 ms of a 4,833 ms
run, 57.4%. That is the ceiling, and it is nearly double the 28.9% ceiling that
refuted the semi-naive plan in Occasion 54.

NOT A PURE WIN, and the reason is nameable rather than hypothetical. `_pure`
answers at budget 0, and budget 0 collapses a left-recursive cell possessively
(`m121.dart:703`) while a positive budget does not, by I41. So for a
left-recursive rule this is NOT merely the cost-0 subset of the full-budget
answer, and the score has to be measured, not assumed. Everywhere else it is
exactly equivalent: `_better` ranks cost first, so wherever a cost-0 way exists
at an ending the full-budget search already keeps it there.
"""

D = '/home/luke/Work/squirrelparser/dart/experiments/recovery/'
src = open(D + 'm121.dart', encoding='utf-8').read()

head = '''// m124.dart -- I73: a prefix that has spent the budget is continued by the pure
// table, not by a repair search whose every answer the fold would discard.
// Generated by mk124.py from m121.dart.
'''
assert src.startswith('// m121.dart --')
src = head + src[src.index('\n') + 1:]

note = '''  /// I73: THE FOLD ALREADY KNOWS THE ANSWER CANNOT COST ANYTHING.
  ///
  /// `w` is a prefix and `_budget` is all this round may spend, so `w.cost ==
  /// _budget` says the prefix has spent it. Every way this element could return
  /// at a positive cost is then discarded two lines below, unread -- measured,
  /// 58.6% of the 9.81M ways such calls produce. What survives is exactly the
  /// repair-free readings, which is exactly what the pure table holds.
  ///
  /// The leading repair `_element` would have allowed cannot survive either: it
  /// costs at least one, and there is nothing left to pay with.
'''

# ------------------------------------------------------------------ the fold
old_seq = '''      for (var w = ways; w != null; w = w.next) {
        for (var x = _element(sub, w.end); x != null; x = x.next) {'''
assert src.count(old_seq) == 1
new_seq = '''      for (var w = ways; w != null; w = w.next) {
        final only = w.cost == _budget;
        for (var x = only ? _pure(sub, w.end) : _element(sub, w.end);
            x != null;
            x = x.next) {'''
src = src.replace(old_seq, new_seq)

# ------------------------------------------------------------ the repetition
old_rep = '''      final w = _at(reach, at)!;
      for (var x = _element(r.subClause, at); x != null; x = x.next) {'''
assert src.count(old_rep) == 1
new_rep = '''      final w = _at(reach, at)!;
      final only = w.cost == _budget;
      for (var x = only ? _pure(r.subClause, at) : _element(r.subClause, at);
          x != null;
          x = x.next) {'''
src = src.replace(old_rep, new_rep)

# The note goes once, above `_seq`, where the fold is explained.
anchor = '  _Ways _seq(List<Clause> subs, int pos) {'
assert src.count(anchor) == 1
src = src.replace(anchor, note + anchor)

out = D + 'm124.dart'
open(out, 'w', encoding='utf-8').write(src)
print('wrote', out)
